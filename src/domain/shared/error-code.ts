  InvalidGameId = 'INVALID_GAME_ID',
  InvalidSchemaVersion = 'INVALID_SCHEMA_VERSION',
  InvalidLevelId = 'INVALID_LEVEL_ID',
  InvalidLevelOrder = 'INVALID_LEVEL_ORDER',
  InvalidLevelName = 'INVALID_LEVEL_NAME',
  InvalidCoordinate = 'INVALID_COORDINATE',
